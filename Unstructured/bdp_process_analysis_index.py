from pyspark.sql import SparkSession
from pyspark.sql import functions as F
from pyspark.sql.window import Window
from google.colab import files  # ⬅ 자동 다운로드용

spark = SparkSession.builder.appName("AnalysisMonthlyTest").getOrCreate()

# ---------------------------------------------
# 1. Load Processed Monthly
# ---------------------------------------------
monthly = spark.read.parquet("/content/processed_blog_monthly_test")

# ---------------------------------------------
# 2. Window 생성
# ---------------------------------------------
w = Window.partitionBy("emd_cd").orderBy("month_start")

# ---------------------------------------------
# 3. Momentum
# ---------------------------------------------
monthly = monthly.withColumn("prev_pd", F.lag("post_density").over(w))
monthly = monthly.withColumn(
    "momentum",
    (F.col("post_density") - F.col("prev_pd")) /
    (F.col("prev_pd") + F.lit(1e-6))
)

# ---------------------------------------------
# 4. Trend Strength
# ---------------------------------------------
monthly = monthly.withColumn("t", F.row_number().over(w))
monthly = monthly.withColumn("t_pd", F.col("t") * F.col("post_density"))
monthly = monthly.withColumn(
    "cov_t_pd",
    F.avg("t_pd").over(w) -
    (F.avg("t").over(w) * F.avg("post_density").over(w))
)
monthly = monthly.withColumn("var_t", F.var_pop("t").over(w))
monthly = monthly.withColumn(
    "trend_strength",
    F.col("cov_t_pd") / (F.col("var_t") + F.lit(1e-6))
)

# ---------------------------------------------
# 5. Analysis Schema
# ---------------------------------------------
analysis = (
    monthly.select(
        F.lit("monthly").alias("period_type"),
        F.col("month_start").alias("period_start"),
        F.last_day("month_start").alias("period_end"),
        "emd_cd",
        "post_density",
        "avg_engagement",
        "avg_sentiment",
        "pos_ratio",
        "sentiment_volatility",
        "topic_diversity",
        "keyword_entropy_avg",
        "semantic_novelty_avg",
        "momentum",
        "trend_strength"
    )
    .withColumn("processed_at", F.current_timestamp())
)

# ---------------------------------------------
# 6. Save as CSV (single file)
# ---------------------------------------------
output_dir = "/content/analysis_blog_monthly_test_csv"

(
    analysis
    .coalesce(1)
    .write
    .option("header", True)
    .mode("overwrite")
    .csv(output_dir)
)

print("📁 Analysis Monthly CSV 생성 완료!")

