from pyspark.sql import SparkSession
from pyspark.sql import functions as F
from pyspark.sql.window import Window

spark = SparkSession.builder.appName("IndexMonthlyTest").getOrCreate()

# ---------------------------------------------
# 1. Load Analysis Monthly
# ---------------------------------------------
analysis = spark.read.parquet("/content/analysis_blog_monthly_test")

# ---------------------------------------------
# 2. z-score normalization helper
# ---------------------------------------------
def z(col):
    return (F.col(col) - F.mean(col).over(Window.partitionBy())) / \
           (F.stddev_pop(col).over(Window.partitionBy()) + F.lit(1e-6))

# ---------------------------------------------
# 3. Score Components
# ---------------------------------------------
index = analysis \
    .withColumn("activity_score", z("post_density") + z("avg_engagement")) \
    .withColumn("sentiment_score", z("avg_sentiment") + z("pos_ratio") - z("sentiment_volatility")) \
    .withColumn("semantic_score", z("topic_diversity") + z("keyword_entropy_avg") + z("semantic_novelty_avg")) \
    .withColumn("trend_score", z("momentum") + z("trend_strength"))

# ---------------------------------------------
# 4. Final Index
# ---------------------------------------------
index = index.withColumn(
    "unstructured_index",
    0.25 * F.col("activity_score") +
    0.25 * F.col("sentiment_score") +
    0.30 * F.col("semantic_score") +
    0.20 * F.col("trend_score")
)

# ---------------------------------------------
# 5. Ranking & metadata
# ---------------------------------------------
w = Window.partitionBy("period_start").orderBy(F.col("unstructured_index").desc())

index = index \
    .withColumn("index_rank", F.row_number().over(w)) \
    .withColumn("index_version", F.lit("v1.0")) \
    .withColumn("calculated_at", F.current_timestamp())

# ---------------------------------------------
# 6. Save
# ---------------------------------------------
index.write.mode("overwrite").parquet("/content/blog_unstructured_index_test")

print("🎉 Index Monthly 생성 완료!")
index.show(20)

