from pyspark.sql.types import FloatType
from pyspark.sql import functions as F
import math

def entropy_py(values):
    if values is None or len(values) == 0:
        return None
    total = len(values)
    counts = {}
    for v in values:
        counts[v] = counts.get(v, 0) + 1
    ent = 0
    for c in counts.values():
        p = c / total
        ent += -p * math.log(p)
    return float(ent)

entropy_udf = F.udf(entropy_py, FloatType())

