def to_json_list(x):
    if x is None:
        return None
    cleaned = []
    for v in x:
        if isinstance(v, (int, float, np.float32, np.float64)):
            cleaned.append(float(v))
        else:
            cleaned.append(str(v))
    return json.dumps(cleaned, ensure_ascii=False)

def keyword_entropy(weights):
    if len(weights) == 0:
        return 0.0
    w = np.array(weights, dtype=float)
    if w.sum() == 0:
        return 0.0
    p = w / w.sum()
    p = p[p > 0]
    return float(-(p * np.log(p)).sum())

def calc_cross_similarity(embeddings):
    n = embeddings.shape[0]
    sims = np.zeros(n, dtype=float)
    if n <= 1:
        return sims
    for i in range(1, n):
        prev = embeddings[:i]
        cur = embeddings[i:i+1]
        cs = cosine_similarity(cur, prev)[0]
        sims[i] = cs.mean()
    return sims

