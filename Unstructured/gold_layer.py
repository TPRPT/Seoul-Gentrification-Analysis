for i in range(0, n_docs, 16):
    if i % 160 == 0 or i + 16 >= n_docs:
        print(f"[Sentiment] 처리 중... {i+1}/{n_docs}")

    batch_texts = docs[i:i+16]
    inputs = sent_tokenizer(
        batch_texts,
        return_tensors="pt",
        padding=True,
        truncation=True,
        max_length=128
    ).to(device)

    with torch.no_grad():
        logits = sent_model(**inputs).logits
        prob = torch.softmax(logits, dim=-1)

    pos_prob = prob[:,1].cpu().numpy()
    score = 2 * pos_prob - 1

    scores.extend(score.tolist())

    for s in score:
        if s > 0.2:
            labels.append("positive")
        elif s < -0.2:
            labels.append("negative")
        else:
            labels.append("neutral")

df["sentiment_score"] = scores
df["sentiment_label"] = labels
