"""1) KoSimCSE (SentenceTransformer) — 문장 임베딩 모델
2) BERTopic — 주제(Topic) 모델링
3) KeyBERT — 문서 내 핵심 키워드 추출
4) TF-IDF — 빈도 기반 키워드(통계적 특징) 추출
5) KcELECTRA — 한국어 감정 분석 모델 (Sentiment)
6) Similarity & Novelty — 신선도/중복도 측정 모델
7) Geocoding Stub (임시 기능)

| 모델                | 역할        | 설명                  |
| ----------------- | --------- | ------------------- |
| KoSimCSE          | 임베딩       | 문장을 의미 벡터로 변환       |
| UMAP              | 차원축소      | 고차원 → 저차원 구조 유지     |
| HDBSCAN           | 클러스터링     | 토픽 자동 생성            |
| BERTopic          | 토픽 모델링    | 토픽 ID, 키워드 생성       |
| KeyBERT           | 의미 기반 키워드 | 문서 핵심 단어 top-5      |
| TF-IDF            | 통계 기반 키워드 | 단어 빈도 기반 top-10     |
| KcELECTRA         | 감정 분석     | 긍정/부정/중립            |
| cosine similarity | 중복도/새로움   | semantic novelty 계산 |

"""

