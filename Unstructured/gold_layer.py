tfidf_vectorizer = TfidfVectorizer(max_features=10000, ngram_range=(1,2), min_df=2)
tfidf_matrix = tfidf_vectorizer.fit_transform(docs)
feature_names = np.array(tfidf_vectorizer.get_feature_names_out())

print("[TF-IDF] 키워드 추출 중...")
tfidf_keywords = []
entropy_list = []
top_k_tfidf = 10

for i in range(n_docs):
    if i % 50 == 0 or i == n_docs - 1:
        print(f"[TF-IDF] 처리 중... {i+1}/{n_docs}")

    row = tfidf_matrix.getrow(i)

    if row.nnz == 0:
        tfidf_keywords.append([])
        entropy_list.append(0.0)
        continue

    data = row.data
    idx = np.argsort(data)[-top_k_tfidf:]
    terms = feature_names[row.indices[idx]]
    weights = data[idx]

    tfidf_keywords.append(list(terms))
    entropy_list.append(keyword_entropy(weights))

df["keyword_list_tfidf"] = [to_json_list(k) for k in tfidf_keywords]
df["keyword_entropy"] = entropy_list
